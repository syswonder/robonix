def _ensure_proto_paths() -> None:
    pkg = Path(__file__).resolve().parent
    sys.path.insert(0, str(pkg))
    d = pkg
    while d.parent != d:
        # Prefer proto_stubs/ (stubs generated with this venv's protobuf version)
        # over proto_gen/ (stubs generated by the system build, may be incompatible).
        pc = d / "proto_stubs"
        pg = d / "proto_gen"
